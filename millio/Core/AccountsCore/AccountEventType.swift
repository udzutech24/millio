import Foundation

/// Тип события счёта. Единственный способ изменить баланс — добавить событие (AC1, AC9).
enum AccountEventType: String, Codable {
    /// Начальный баланс/остаток на момент создания счёта (или сальдо переноса).
    case openingBalance
    /// Приход (для долга/кредита — платёж, уменьшающий обязательство).
    case income
    /// Расход.
    case expense
    /// Исходящая нога перевода между счетами (см. `transferID`, инвариант Σ=0, AC12).
    case transferOut
    /// Входящая нога перевода.
    case transferIn
    /// Покупка актива (рыночный счёт): увеличивает quantity.
    case buy
    /// Продажа актива: уменьшает quantity.
    case sell
    /// Начисленный процент (вклад).
    case interest
    /// Дивиденд (рыночный счёт).
    case dividend
    /// Комиссия/удержание.
    case fee
    /// Досрочное/дополнительное погашение (кредит/долг).
    case extraPayment
    /// Пролонгация вклада на новый срок (не меняет баланс сама по себе).
    case rollover
    /// Переоценка ручного актива — фиксирует НОВУЮ полную стоимость (не дельту).
    case revaluation
    /// Ручная корректировка баланса — хранит ДЕЛЬТУ, не абсолютное значение.
    case adjustment
    /// Смена валюты счёта. Курс фиксируется навсегда, события ДО него не переписываются (AC11/AC15).
    case redenomination
}
