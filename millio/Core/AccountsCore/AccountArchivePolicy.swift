import Foundation

/// Логика предупреждения при архивации счёта нового ядра (S8 в плане, задача 5 Фазы 5): «ступенька
/// вниз» на графике после закрытия ненулевого счёта пугает пользователя («пропали деньги»).
/// Decimal-версия `FinanceAccountArchivePolicy` (старый мир, Double) — новое ядро считает всё в
/// Decimal (Т9 в плане), конвертация в Double на границе UI недопустима для решения «показывать
/// предупреждение или нет» (риск копеечного ложного срабатывания на границе порога).
enum AccountArchivePolicy {
    /// Порог, ниже которого баланс считается «фактически нулевым» (защита от плавающей копейки).
    private static let zeroThreshold: Decimal = 0.01

    /// Нужно ли перед архивацией предложить выбор «сначала перевести остаток» / «закрыть с остатком».
    static func shouldWarnBeforeArchiving(balance: Decimal) -> Bool {
        abs(balance) >= zeroThreshold
    }
}
