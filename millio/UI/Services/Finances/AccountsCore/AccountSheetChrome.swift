import SwiftUI

extension View {
    /// Единая «рамка» листов зоны счетов: детент + индикатор перетаскивания.
    /// Раньше детенты стояли у половины листов — остальные открывались во весь экран
    /// и без ручки, из-за чего одинаковые по смыслу формы выглядели по-разному.
    ///
    /// По умолчанию `.large`: во всех этих формах есть поле ввода, а на среднем детенте
    /// клавиатура перекрывает его — это уже ловили на листе реквизитов вклада.
    /// `.medium` уместен только там, где клавиатуры нет вовсе.
    func accountSheetChrome(detent: PresentationDetent = .large) -> some View {
        presentationDetents([detent])
            .presentationDragIndicator(.visible)
    }
}
